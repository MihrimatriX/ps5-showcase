// Pulls real movies from TMDB into content/movies.ts.
// Needs a TMDB API read access token in .env.local (TMDB_TOKEN, from themoviedb.org/settings/api), then: npm run sync:movies
// The TMDB access and the movie mapping live in lib/tmdb.ts, shared with the store's movie search.
import { writeFileSync } from "node:fs";
import { movies, searchMovies, tmdb } from "../lib/tmdb.ts";

try {
  process.loadEnvFile(".env.local");
} catch {}
if (!process.env.TMDB_TOKEN) {
  console.error("TMDB_TOKEN missing: add it to .env.local");
  process.exit(1);
}

/** Movies the visitor already owns: the Movies tab, in order. Titles are matched against TMDB's search. */
const TITLES = [
  // TODO(human)
];

const owned = [];
for (const title of TITLES) {
  const [hit] = await searchMovies(title, 1);
  if (hit) owned.push(hit);
  else console.warn(`not found on TMDB: ${title}`);
}

// The store: the best-rated movies the visitor doesn't own yet, then the upcoming ones still to come out.
const today = new Date().toISOString().slice(0, 10);
const list = (path, params = {}) => tmdb(path, { language: "en-US", ...params }).then((r) => r.results);
const store = [
  ...(await list("movie/top_rated")),
  ...(await list("movie/top_rated", { page: "2" })),
].slice(0, 24);
store.push(...(await list("movie/upcoming", { region: "TR" })).filter((m) => m.release_date > today).slice(0, 8));
const fresh = store.filter((m, i) => !owned.some((o) => o.id === m.id) && store.findIndex((x) => x.id === m.id) === i);

const all = [...(await movies(owned, true)), ...(await movies(fresh))];
writeFileSync(
  "content/movies.ts",
  `// Generated by scripts/sync-tmdb.mjs from TMDB. Do not edit by hand: run \`npm run sync:movies\`.\nimport type { Project } from "@/lib/types";\n\nexport const movies: Project[] = ${JSON.stringify(all, null, 2)};\n`,
);
console.log(`Wrote ${all.length} movies to content/movies.ts (${owned.length} owned, ${all.length - owned.length} in the store)`);
